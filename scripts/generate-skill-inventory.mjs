#!/usr/bin/env node
/**
 * Regenerates skills/mlz-design/references/* from source.
 *
 * The skill is what consuming repos read instead of asking me to "go look at
 * the design system". If it drifts from src/, it is worse than nothing — so it
 * is generated, never hand-edited, and CI fails when it is stale.
 *
 *   bun run skill:inventory          # write
 *   bun run skill:inventory --check  # exit 1 if out of date (CI)
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
const OUT = join(ROOT, "skills/mlz-design/references");
const check = process.argv.includes("--check");

const GROUP_BLURB = {
  brand:
    "Identity and personality. Not generic UI — reach for these when a page needs to feel like MLZ.",
  "data-display": "Read-only presentation of values, text and tabular data.",
  feedback: "State of the system: loading, empty, success, failure.",
  forms:
    "Anything the user types, picks or toggles. Controls share the sm/default/lg/icon size scale.",
  layout:
    "Structure and navigation. Layout primitives use the sm/md/lg breakpoint scale — do not mix with the control scale.",
  overlay: "Anything that paints above the page. All Radix-backed.",
};

/** Public component exports, in source order, excluding types. */
function exportedNames() {
  const src = readFileSync(join(ROOT, "src/index.ts"), "utf8");
  return [...src.matchAll(/export\s*(type)?\s*\{([^}]*)\}/gs)]
    .filter((m) => !m[1])
    .flatMap((m) => m[2].split(","))
    .map((x) =>
      x
        .trim()
        .split(/\s+as\s+/)
        .pop(),
    )
    .filter((n) => /^[A-Z]/.test(n));
}

/** Component files per group, ignoring tests, stories and test-env helpers. */
function filesByGroup() {
  const base = join(ROOT, "src/components");
  return Object.fromEntries(
    readdirSync(base, { withFileTypes: true })
      .filter((d) => d.isDirectory())
      .map((d) => [
        d.name,
        readdirSync(join(base, d.name))
          .filter((f) => f.endsWith(".tsx") && !/\.(test|stories)\./.test(f))
          .map((f) => f.replace(/\.tsx$/, ""))
          .sort(),
      ]),
  );
}

/**
 * First JSDoc sentence of the component's own declaration.
 *
 * Matching the first JSDoc in the file is wrong — that is almost always the
 * first prop in the Props interface, which produced entries like
 * "FloatingMarks — How many marks to scatter."
 */
function blurb(group, file, name) {
  const path = join(ROOT, "src/components", group, `${file}.tsx`);
  if (!existsSync(path)) return "";
  const src = readFileSync(path, "utf8");
  const decl = new RegExp(
    // The body must not contain `*/`, or a lazy match happily spans from an
    // earlier prop's JSDoc all the way to the declaration.
    String.raw`/\*\*((?:(?!\*/)[\s\S])*?)\*/\s*(?:export\s+)?(?:const|function)\s+${name}\b`,
  );
  const doc = src.match(decl);
  if (!doc) return "";
  const text = doc[1]
    .split("\n")
    .map((l) => l.replace(/^\s*\*\s?/, "").trim())
    .filter((l) => l && !l.startsWith("@"))
    .join(" ");
  const sentence = text.split(/(?<=\.)\s/)[0] ?? "";
  return sentence.length > 160 ? `${sentence.slice(0, 157)}…` : sentence;
}

/** Semantic tokens only: theme.css minus brand primitives and the @theme re-exports. */
function semanticTokens() {
  const css = readFileSync(join(ROOT, "src/styles/theme.css"), "utf8");
  const names = [...css.matchAll(/^\s*(--[a-z0-9-]+)\s*:/gm)]
    .map((m) => m[1])
    .filter((n) => !n.startsWith("--mlz-") && !n.startsWith("--color-"));
  return [...new Set(names)].sort();
}

function bucket(tokens) {
  const of = (re) => tokens.filter((t) => re.test(t));
  return {
    "Surfaces & text": of(/^--(background|foreground|card|popover|muted|secondary|overlay)/),
    "Accent & primary": of(/^--(accent|primary)/),
    Signals: of(/^--(success|warning|danger|destructive|info)/),
    "Lines & focus": of(/^--(border|input|ring)/),
    Type: of(/^--font-/),
    "Radius & shadow": of(/^--(radius|shadow)/),
    Motion: of(/^--(dur|ease|animate)-/),
  };
}

const exported = new Set(exportedNames());
const groups = filesByGroup();

let components = `<!-- GENERATED by scripts/generate-skill-inventory.mjs — do not edit. -->
# Component inventory

Every component below already exists. **Check here before writing a new one.**
All are imported from \`@martinzachariassen/design\`.
Compound parts (\`CardHeader\`, \`DialogTrigger\`, …) are exported alongside their
root and omitted here; import what you need from the same package.

`;

for (const [group, files] of Object.entries(groups).sort()) {
  components += `## ${group}\n\n${GROUP_BLURB[group] ?? ""}\n\n`;
  for (const file of files) {
    const pascal = file.replace(/(^|-)([a-z])/g, (_, __, c) => c.toUpperCase());
    if (!exported.has(pascal)) continue;
    const b = blurb(group, file, pascal);
    components += `- **${pascal}**${b ? ` — ${b}` : ""}\n`;
  }
  components += "\n";
}

const buckets = bucket(semanticTokens());
let tokens = `<!-- GENERATED by scripts/generate-skill-inventory.mjs — do not edit. -->
# Semantic token reference

The only layer you may read or override. Brand primitives (\`--mlz-*\`) are
private to the system; a consuming app that references one has bypassed theming
and will not follow accent or dark mode.

Every token below is also a Tailwind utility (\`bg-card\`, \`text-muted-foreground\`,
\`ring-ring\`, \`font-mono\`, \`rounded-lg\`) — the token and the utility are the
same thing.

`;

for (const [name, list] of Object.entries(buckets)) {
  if (!list.length) continue;
  tokens += `## ${name}\n\n${list.map((t) => `\`${t}\``).join(" · ")}\n\n`;
}

tokens += `## Accent families

\`data-accent\` on \`<html>\`: **blue · cyan · green · ink · rust**.
Set via \`ThemeProvider\` / \`AccentPicker\`, never hardcoded in a component.
`;

// Trailing blank lines make `git am` complain about whitespace errors.
components = `${components.trimEnd()}\n`;
tokens = `${tokens.trimEnd()}\n`;

const targets = [
  [join(OUT, "components.md"), components],
  [join(OUT, "tokens.md"), tokens],
];

let stale = false;
for (const [path, content] of targets) {
  const current = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (current === content) continue;
  stale = true;
  if (check) console.error(`stale: ${path}`);
  else {
    mkdirSync(OUT, { recursive: true });
    writeFileSync(path, content);
  }
}

if (check && stale) {
  console.error("\nRun `bun run skill:inventory` and commit the result.");
  process.exit(1);
}
if (!check) console.log(`skill inventory written → ${OUT}`);
